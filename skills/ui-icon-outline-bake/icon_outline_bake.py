#!/usr/bin/env python3
"""Bake a thick UNIFORM outline into UI icons (same navy as the plate outline). Idempotent via a ledger.
python -I icon_outline_bake.py --ledger docs/ui-style/icon_outline_ledger.json --cs OUT.cs --ratio 0.055 FILE_OR_GLOB...
Icon content is scaled down so icon + outline fit the ORIGINAL canvas (layouts do not move). Skips files already in the ledger,
fully opaque rectangles and anything over --max-px. Writes the baked names list as a generated C# HashSet (runtime ring off for them)."""
import sys, os, json, glob, argparse, hashlib
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
NAVY = (8, 13, 28)
def bake(path, ratio):
    im = Image.open(path).convert('RGBA'); w, h = im.size; m = max(w, h)
    a0 = np.asarray(im)[..., 3] / 255.0
    if a0.mean() > 0.92 or m > 640: return None
    T = max(3, round(ratio * m)); s = (m - 2 * T) / m
    nw, nh = max(1, round(w * s)), max(1, round(h * s))
    ic = im.resize((nw, nh), Image.LANCZOS)
    canvas = Image.new('RGBA', (w, h), (0, 0, 0, 0)); canvas.alpha_composite(ic, ((w - nw) // 2, (h - nh) // 2))
    a = np.asarray(canvas)[..., 3] / 255.0
    K = 3
    big = np.asarray(Image.fromarray((a * 255).astype(np.uint8)).resize((w * K, h * K), Image.BICUBIC), dtype=np.float32) / 255
    outside = ndi.distance_transform_edt(big < 0.5)
    ring = np.clip(T * K + 0.5 - outside, 0, 1)
    ring = np.maximum(ring, big)
    ring_s = np.asarray(Image.fromarray((ring * 255).astype(np.uint8)).resize((w, h), Image.LANCZOS), dtype=np.float32) / 255
    out = np.zeros((h, w, 4), dtype=np.float32); out[..., :3] = np.array(NAVY, dtype=np.float32) / 255; out[..., 3] = ring_s
    base = Image.fromarray((out * 255).astype(np.uint8)); base.alpha_composite(canvas)
    return base
if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('files', nargs='+'); p.add_argument('--ledger', required=True); p.add_argument('--cs'); p.add_argument('--ratio', type=float, default=0.055)
    a = p.parse_args()
    led = json.load(open(a.ledger)) if os.path.exists(a.ledger) else {}
    files = []
    for f in a.files: files += glob.glob(f)
    done = skipped = 0
    for f in sorted(set(files)):
        key = os.path.basename(f)
        if key in led: skipped += 1; continue
        r = bake(f, a.ratio)
        if r is None: led[key] = 'skipped'; skipped += 1; continue
        r.save(f); led[key] = hashlib.md5(open(f, 'rb').read()).hexdigest()[:8]; done += 1
    json.dump(led, open(a.ledger, 'w'), indent=1, sort_keys=True)
    names = sorted(os.path.splitext(k)[0] for k, v in led.items() if v != 'skipped')
    if a.cs:
        body = ',\n            '.join('"%s"' % n for n in names)
        open(a.cs, 'w', encoding='utf-8', newline='').write('using System.Collections.Generic;\n\nnamespace Game.DigEgg\n{\n    // GENERATED by skills/ui-icon-outline-bake/icon_outline_bake.py: icons with a baked uniform outline (runtime outline ring is skipped for them).\n    public static class Dig_Ui_IconOutlineBaked\n    {\n        public static readonly HashSet<string> Names = new()\n        {\n            ' + body + '\n        };\n        public static bool Has(string spriteName) => spriteName != null && Names.Contains(spriteName);\n    }\n}\n')
    print('baked', done, 'skipped', skipped, 'total baked names', len(names))
