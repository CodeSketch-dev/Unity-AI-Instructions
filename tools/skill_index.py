"""Print a markdown index of a skills directory, grouped by name prefix.

Usage: py -I tools/skill_index.py <skills-dir> > skills/INDEX.md
"""
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from skill_lint import parse_frontmatter  # noqa: E402


def build_index(root):
    groups = defaultdict(list)
    for folder in sorted(os.listdir(root)):
        path = os.path.join(root, folder, "SKILL.md")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as f:
            fm, _ = parse_frontmatter(f.read())
        desc = (fm or {}).get("description", "").strip()
        groups[folder.split("-", 1)[0]].append("- %s - %s" % (folder, desc))
    out = ["# Skills index (generated by tools/skill_index.py; do not edit)", ""]
    for prefix in sorted(groups):
        out.append("## %s" % prefix)
        out.extend(groups[prefix])
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 2 or not os.path.isdir(sys.argv[1]):
        print("usage: skill_index.py <skills-dir>", file=sys.stderr)
        sys.exit(2)
    sys.stdout.reconfigure(encoding="utf-8")
    print(build_index(sys.argv[1]))
